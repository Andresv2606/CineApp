package com.example.cineapp.models;

public class Cine {

    private int id_cine;
    private String nombre;
    private String direccion;
    private String telefono;

    public int getId_cine() {
        return id_cine;
    }

    public String getNombre() {
        return nombre;
    }

    public String getDireccion() {
        return direccion;
    }

    public String getTelefono() {
        return telefono;
    }
}
